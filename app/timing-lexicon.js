  var SKY_FLIP = { conjunct: 'opposite', opposite: 'conjunct', sextile: 'trine', trine: 'sextile', square: 'square' };
  /* A reading for two moving bodies in aspect overhead. Order does not matter,
     the South Node is read as the North Node contact it mirrors, and the two
     nodes with each other answer null: that pair is always exactly opposite. */
  function sky(a, asp, b) {
    var k = aspKey(asp);
    if (ASPECTS.indexOf(k) === -1) return null;
    var aN = a === 'South Node', bN = b === 'South Node';
    if (aN) { a = 'North Node'; k = SKY_FLIP[k]; }
    if (bN) { b = 'North Node'; k = SKY_FLIP[k]; }
    if (a === b) return null;
    var ia = MOVERS.indexOf(a), ib = MOVERS.indexOf(b);
    if (ia === -1 || ib === -1) return null;
    var e = SKY[ia < ib ? a + '|' + b : b + '|' + a];
    if (!e) return null;
    return { text: e[aspClass(k)], ask: e.ask, asp: k };
  }

