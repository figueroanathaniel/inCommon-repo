#!/usr/bin/env python3
"""Build dated JPL vector-derived point tables, without Swiss positional data.
Usage: PYTHONPATH=<jplephem:pyerfa> python tools/build-jpl-derived-points.py <de440s.bsp>
Time-scale compatibility samples are read from ut1-tt-reference.json.
"""
import sys, json, hashlib, importlib.util
from pathlib import Path
import numpy as np
root=Path(__file__).resolve().parent.parent
spec=importlib.util.spec_from_file_location('geometry', root/'tools/lib/jpl-point-geometry.py');gmod=importlib.util.module_from_spec(spec);spec.loader.exec_module(gmod)
kernel=Path(sys.argv[1]); g=gmod.Geometry(kernel)
rows=np.array(json.loads((root/'tools/fixtures/ut1-tt-reference.json').read_text())['rows'])
def tt(t):return t+2451545+np.interp(t,rows[:,0],rows[:,1])/86400
minimum=-36524.5; maximum=36524.5
series={}
for name,step in [('apogee',.25)]+[(n,4) for n in gmod.PLANETS]:
 start=np.floor(minimum/step)*step-2*step; end=np.ceil(maximum/step)*step+2*step
 times=np.arange(start,end+step/2,step);jd=tt(times)
 lon=g.apogee(jd) if name=='apogee' else g.node(name,jd)
 series[name]={'start':float(start),'step':step,'values':np.round(lon,8).tolist()}
 print(name,len(times),flush=True)
metadata={'source':'NASA/JPL DE440s position and velocity vectors','kernelSha256':hashlib.sha256(kernel.read_bytes()).hexdigest(), 'frame':'Tropical ecliptic of date; explicit dynamical J2000 constructed-point rotation; geometric heliocentric osculating ascending nodes; geocentric osculating lunar apogee', 'time':'J2000 UT days with declared TT−UT compatibility samples', 'minT':minimum,'maxT':maximum}
text='''/*! JPL-derived geometric nodes and lunar apogee. Generated by
 * tools/build-jpl-derived-points.py; no Swiss code or positional tables.
 * Four-point angular interpolation; reject dates outside 1900 to 2100.
 */
(function(root,factory){if(typeof module==='object'&&module.exports)module.exports=factory();else root.JPLDerivedPoints=factory();})(typeof window!=='undefined'?window:globalThis,function(){
'use strict';
const metadata = '''+json.dumps(metadata,separators=(',',':'))+''';
const series = '''+json.dumps(series,separators=(',',':'))+''';
const norm=x=>((x%360)+360)%360;
function at(name,t){
 if(!Number.isFinite(t)||t<metadata.minT||t>metadata.maxT)return null;
 const s=series[name];if(!s)return null;
 const k=Math.floor((t-s.start)/s.step),u=(t-s.start)/s.step-k;
 if(k<1||k+2>=s.values.length)return null;
 const p1=s.values[k],near=(a,b)=>a-Math.round((a-b)/360)*360;
 const p0=near(s.values[k-1],p1),p2=near(s.values[k+1],p1),p3=near(s.values[k+2],p2);
 return norm(p0*(-u*(u-1)*(u-2)/6)+p1*((u+1)*(u-1)*(u-2)/2)+p2*(-(u+1)*u*(u-2)/2)+p3*((u+1)*u*(u-1)/6));
}
return Object.freeze({metadata,apogee:t=>at('apogee',t),node:(name,t)=>at(name,t)});
});
'''
(root/'app/jpl-derived-points.js').write_text(text)
print('Module bytes',len(text.encode()),flush=True)
