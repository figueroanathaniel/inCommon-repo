#!/usr/bin/env node
/* check-astral-bodies.js: the ten astral bodies, measured against JPL Horizons.
 *
 * WHY THIS GATE EXISTS. Every reading in the app stands on ten longitudes, and
 * for as long as the app existed nothing compared them with anything outside
 * the build. The asteroids were held to NASA to a twentieth of a degree while
 * the Moon under them came from a two term series. It measured 1.3 degrees on
 * the Moon and 6.5 on Mars against this fixture, and that was enough to move a
 * Human Design Type for about one birth in twelve. Nineteen gates were green
 * the whole time, because every one of them tested what it was pointed at.
 *
 * WHAT IT RUNS. lonRaw() lifted out of the app file, exactly as
 * bench-ephemeris.js lifts it, with the vendored astronomy-engine file loaded
 * as window.Astronomy the way the helmet loads it. A second copy of the
 * arithmetic here would measure the second copy.
 *
 * WHAT IT ASSERTS.
 *   1. Every body is within CEILING of all 1,975 Horizons positions, 1900 to
 *      2100 (tools/fixtures/astral-bodies-horizons.json, generated by
 *      fetch-astral-bodies.js).
 *   2. With window.Astronomy removed the same comparison FAILS. That is the
 *      proof this gate can go red, and that the library is what passes it.
 *   2b. Mars to Pluto, which the app interpolates off a four day grid of library
 *      positions, is within GRID_CEILING of the library asked directly, at a
 *      quarter day through every crossing of 0 Aries in the fixture.
 *   3. The vendored file is the bytes that were measured: its SHA-256 is
 *      pinned, so an edit to it is a failure rather than a silent change of
 *      ephemeris.
 *   4. A time that is not finite answers NaN, as the series did, instead of
 *      throwing: the library throws where the series did not.
 *   5. The two seams that fail silently are in place: modulesReady() waits for
 *      window.Astronomy, and app/sw.js precaches the file.
 *
 * It refuses to report green when it cannot see: a missing body, a thin
 * fixture, or a lifted lonRaw that returns nothing sensible is a failure.
 *
 * Usage: node tools/check-astral-bodies.js [--verbose]
 */
'use strict';

const fs = require('fs');
const path = require('path');
const crypto = require('crypto');

const repo = path.resolve(__dirname, '..');
const APP = path.join(repo, 'app', 'inCommonApp v2.dc.html');
const LIB_NAME = 'astronomy-engine-2.1.19.min.js';
const LIB = path.join(repo, 'app', LIB_NAME);
const LIB_SHA256 = 'f41139a87941ea017ab902b954c9389fa27ea72083d7fab4971756d7769d14e6';
const FIX = path.join(repo, 'tools', 'fixtures', 'astral-bodies-horizons.json');
const verbose = process.argv.indexOf('--verbose') !== -1;

/* A thirtieth of a Human Design line (0.9375 degrees) and two arcminutes. The
   library measures 0.023 on the Moon and under 0.006 on the rest, so this has
   room for a Horizons revision and none for a real regression. */
const CEILING = 0.03;
const BODIES = ['Sun', 'Moon', 'Mercury', 'Venus', 'Mars', 'Jupiter', 'Saturn', 'Uranus', 'Neptune', 'Pluto'];
const MIN_PER_BODY = 1900;

const failures = [];
const fail = m => failures.push(m);

/* ---------- lift the ephemeris out of the app class ---------- */

const src = fs.readFileSync(APP, 'utf8');
const lines = src.split('\n');
const lineOf = re => { for (let i = 0; i < lines.length; i++) if (re.test(lines[i])) return i + 1; return -1; };
function blockAt(n) {
  const anchor = src.indexOf(lines[n - 1]);
  let depth = 0, j = src.indexOf('{', anchor);
  for (; j < src.length; j++) {
    if (src[j] === '{') depth++;
    else if (src[j] === '}') { depth--; if (depth === 0) break; }
  }
  return src.slice(anchor, j + 1);
}
const FIELDS = { RAD: /^\s{2}RAD = Math\.PI/, PL_EL: /^\s{2}PL_EL = \{/, EARTH_EL: /^\s{2}EARTH_EL = \[/, ASTEROIDS: /^\s{2}ASTEROIDS = \[/ };
const BLOCKS = { norm360: /^\s{2}norm360\(x\)/, lonRaw: /^\s{2}lonRaw\(name, t\)/, minorLon: /^\s{2}minorLon\(el, t\)/ };
const pieces = [], missing = [];
for (const [k, re] of Object.entries(FIELDS)) { const n = lineOf(re); if (n === -1) missing.push(k); else pieces.push(lines[n - 1]); }
for (const [k, re] of Object.entries(BLOCKS)) { const n = lineOf(re); if (n === -1) missing.push(k); else pieces.push(blockAt(n)); }
if (missing.length) {
  console.error('check-astral-bodies: FAIL\n  could not lift out of the app file: ' + missing.join(', ') +
    '\n  The shape of the class changed. bench-ephemeris.js lifts the same pieces and will need the same fix.');
  process.exit(1);
}

const libBytes = fs.readFileSync(LIB);
const Astronomy = require(LIB);
global.window = { MinorBodies: null, MinorBodyElements: null, Astronomy };
let Eph;
try { Eph = eval('(class Eph {\n' + pieces.join('\n') + '\n})'); }
catch (e) { console.error('check-astral-bodies: FAIL\n  the lifted ephemeris does not parse: ' + e.message); process.exit(1); }
const app = new Eph();

/* ---------- the fixture, and whether it can see ---------- */

const fix = JSON.parse(fs.readFileSync(FIX, 'utf8')).horizons || {};
for (const b of BODIES) {
  const rows = fix[b] || [];
  if (rows.length < MIN_PER_BODY) fail(b + ': ' + rows.length + ' reference positions, fewer than ' + MIN_PER_BODY);
  else {
    const t0 = rows[0][0], t1 = rows[rows.length - 1][0];
    if (t0 > -36500 || t1 < 36500) fail(b + ': the fixture spans t ' + t0 + ' to ' + t1 + ', not 1900 to 2100');
  }
}

const norm = x => ((x % 360) + 360) % 360;
const sep = (a, b) => { const d = Math.abs(norm(a - b)); return d > 180 ? 360 - d : d; };
function measure() {
  const out = {};
  for (const b of BODIES) {
    let worst = 0, sq = 0, n = 0, bad = 0;
    for (const [t, lon] of fix[b] || []) {
      const v = app.lonRaw(b, t);
      if (typeof v !== 'number' || !isFinite(v)) { bad++; continue; }
      const d = sep(v, lon); if (d > worst) worst = d; sq += d * d; n++;
    }
    out[b] = { worst, rms: n ? Math.sqrt(sq / n) : NaN, n, bad };
  }
  return out;
}

/* ---------- 1. the app, as it ships ---------- */

const live = measure();
for (const b of BODIES) {
  const m = live[b];
  if (m.bad) fail(b + ': lonRaw returned no number for ' + m.bad + ' instants');
  if (m.worst > CEILING) fail(b + ': worst ' + m.worst.toFixed(4) + ' degrees against Horizons, over the ceiling of ' + CEILING);
}

/* ---------- 2. the fallback must fail, or this gate proves nothing ---------- */

window.Astronomy = null;
const fallback = measure();
window.Astronomy = Astronomy;
const fallbackOver = BODIES.filter(b => fallback[b].worst > CEILING);
if (!fallbackOver.length) fail('with window.Astronomy removed every body still passes: the gate is not measuring the library');

/* ---------- 2b. the grid against the library it interpolates ----------
   Mars outward are read off a four day grid of library positions. Horizons
   samples every 37 days, so a fault that only shows within a few days of 0
   Aries can fall between them. Walk every crossing in the fixture at a quarter
   day, and the whole span at an interval that never lines up with the grid,
   against the library asked directly. */

const GRIDDED = ['Mars', 'Jupiter', 'Saturn', 'Uranus', 'Neptune', 'Pluto'];
const GRID_CEILING = 1e-3;
const grid = {};
for (const b of GRIDDED) {
  const direct = t => norm(Astronomy.Ecliptic(Astronomy.GeoVector(b, Astronomy.MakeTime(t), true)).elon);
  const g = grid[b] = { worst: 0, n: 0, crossings: 0 };
  const look = t => { const d = sep(app.lonRaw(b, t), direct(t)); if (d > g.worst) g.worst = d; g.n++; };
  const rows = fix[b] || [];
  for (let i = 1; i < rows.length; i++) {
    if (Math.abs(rows[i][1] - rows[i - 1][1]) < 180) continue;
    g.crossings++;
    for (let t = rows[i - 1][0]; t <= rows[i][0]; t += 0.25) look(t);
  }
  for (let t = -36500; t < 36500; t += 73.137) look(t);
  if (!g.crossings) fail(b + ': no crossing of 0 Aries in the fixture, so the unwrap is untested');
  if (g.worst > GRID_CEILING) fail(b + ' off its grid: worst ' + g.worst.toExponential(2) + ' degrees from the library, over ' + GRID_CEILING);
}
const gridWorst = Math.max(...GRIDDED.map(b => grid[b].worst));
const gridN = GRIDDED.reduce((s, b) => s + grid[b].n, 0), crossings = GRIDDED.reduce((s, b) => s + grid[b].crossings, 0);

/* ---------- 3. the bytes that were measured ---------- */

const sha = crypto.createHash('sha256').update(libBytes).digest('hex');
if (sha !== LIB_SHA256) fail(LIB_NAME + ' is not the file that was measured (sha256 ' + sha.slice(0, 16) + '...)');

/* ---------- 4. the seams that fail silently ---------- */

const ready = lines[lineOf(/^\s{2}modulesReady\(\)/) - 1] || '';
if (ready.indexOf('window.Astronomy') === -1) fail('modulesReady() does not wait for window.Astronomy, so a chart can be memoised from the fallback');
const tags = (src.match(new RegExp('<script src="\\./' + LIB_NAME.replace(/\./g, '\\.') + '"></script>', 'g')) || []).length;
if (tags !== 1) fail('the app declares ' + LIB_NAME + ' ' + tags + ' times, not once');
/* The library throws on a time that is not finite; the series it replaced
   answered NaN. An unparsed birth date must still answer NaN rather than throw
   out of a render. */
for (const b of BODIES) for (const t of [NaN, Infinity, undefined]) {
  try { const v = app.lonRaw(b, t); if (!Number.isNaN(v)) fail(b + ' at t=' + t + ' answered ' + v + ', not NaN'); }
  catch (e) { fail(b + ' at t=' + t + ' threw (' + String(e).slice(0, 60) + '), where the series answered NaN'); }
}
const sw = fs.readFileSync(path.join(repo, 'app', 'sw.js'), 'utf8');
if (sw.indexOf("'./" + LIB_NAME + "'") === -1) fail('app/sw.js does not precache ' + LIB_NAME + ', so an offline launch waits out the boot and draws from the fallback');

/* ---------- report ---------- */

const HW = require(path.join(repo, 'app', 'hd-wheel.js'));
let lineDiff = 0, gateDiff = 0, total = 0;
for (const b of BODIES) for (const [t, lon] of fix[b] || []) {
  const a = HW.gateLine(app.lonRaw(b, t)), h = HW.gateLine(lon); total++;
  if (a.gate !== h.gate) gateDiff++;
  if (a.gate !== h.gate || a.line !== h.line) lineDiff++;
}

const status = failures.length ? 'FAIL' : 'ok';
console.log('check-astral-bodies: ' + status);
for (const f of failures) console.log('  ' + f);
console.log('  body       worst deg    rms deg   worst arcsec   old series worst');
for (const b of BODIES) {
  const m = live[b], o = fallback[b];
  console.log('  ' + b.padEnd(9) + m.worst.toFixed(4).padStart(10) + m.rms.toFixed(4).padStart(11) +
    (m.worst * 3600).toFixed(1).padStart(14) + o.worst.toFixed(2).padStart(19));
}
console.log('  ceiling             ' + CEILING + ' degrees, every body, ' + total + ' positions 1900 to 2100');
console.log('  gate / line moved   ' + gateDiff + ' / ' + lineDiff + ' of ' + total + ' (reference boundary crossings, not failures)');
console.log('  four day grid       ' + gridWorst.toExponential(2) + ' degrees from the library at worst, Mars to Pluto, ' + gridN + ' instants, ' + crossings + ' crossings of 0 Aries');
console.log('  old series          over the ceiling on ' + fallbackOver.length + ' of ' + BODIES.length + ' bodies, so this gate can go red');
if (verbose) console.log('  library             ' + LIB_NAME + ' sha256 ' + sha);
process.exit(failures.length ? 1 : 0);
