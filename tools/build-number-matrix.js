#!/usr/bin/env node
/* build-number-matrix.js: writes app/number-matrix.js from the owner's Book of
 * Numbers matrix, docs/source/book-of-numbers-matrix.csv.
 *
 * The matrix is the owner's writing (19 October 2026): every compound from 10
 * to 99, its root, the reduction that reaches it, a title, a category (Master
 * Number, Karmic Debt, Elite Auspicious, Standard Sub-Frequency) and a
 * description. It is generated, never typed, for the same reason
 * hd-topology.js and minor-body-elements.js are: ninety rows copied by hand
 * are ninety chances to put a title on the wrong number. Change the CSV, then
 * run this.
 *
 * It refuses a matrix that is not whole: a compound missing or duplicated, a
 * root that is not the compound's own digital root, a category it does not
 * know, a field left empty, or a dash.
 *
 * Usage: node tools/build-number-matrix.js [--check]
 *   --check  write nothing, exit 1 if app/number-matrix.js is not what this
 *            would write.
 */
'use strict';

const fs = require('fs');
const path = require('path');

const repo = path.resolve(__dirname, '..');
const SRC = path.join(repo, 'docs', 'source', 'book-of-numbers-matrix.csv');
const OUT = path.join(repo, 'app', 'number-matrix.js');
const CATEGORIES = ['Master Number', 'Karmic Debt', 'Elite Auspicious', 'Standard Sub-Frequency'];
const DASH = new RegExp('[' + String.fromCharCode(8212, 8211) + ']');

function fail(msg) { console.error('build-number-matrix: ' + msg); process.exit(1); }

/* RFC 4180 enough for this file: quoted fields, doubled quotes inside them. */
function parse(text) {
  const rows = []; let row = [], f = '', q = false;
  for (let i = 0; i < text.length; i++) {
    const c = text[i];
    if (q) {
      if (c === '"' && text[i + 1] === '"') { f += '"'; i++; }
      else if (c === '"') q = false;
      else f += c;
    } else if (c === '"') q = true;
    else if (c === ',') { row.push(f); f = ''; }
    else if (c === '\n' || c === '\r') {
      if (c === '\r' && text[i + 1] === '\n') i++;
      row.push(f); f = '';
      if (row.some(x => x !== '')) rows.push(row);
      row = [];
    } else f += c;
  }
  if (f !== '' || row.length) { row.push(f); if (row.some(x => x !== '')) rows.push(row); }
  return rows;
}

function digitalRoot(n) { while (n > 9) n = String(n).split('').reduce((a, c) => a + +c, 0); return n; }

const rows = parse(fs.readFileSync(SRC, 'utf8'));
const head = rows.shift().map(s => s.trim());
const want = ['Number', 'Base Root', 'Reduction Math', 'Title', 'Category', 'Description'];
if (head.join('|') !== want.join('|')) fail('header is "' + head.join(',') + '", expected "' + want.join(',') + '"');

const seen = {};
const entries = rows.map((r, i) => {
  if (r.length !== 6) fail('row ' + (i + 2) + ' has ' + r.length + ' fields');
  const [n, root, math, title, category, desc] = r.map(s => s.trim());
  const num = +n, rt = +root;
  if (!/^\d{2}$/.test(n) || num < 10 || num > 99) fail('row ' + (i + 2) + ': number "' + n + '" is not 10 to 99');
  if (seen[num]) fail('compound ' + num + ' appears twice');
  seen[num] = true;
  if (rt !== digitalRoot(num)) fail(num + ': root ' + rt + ' is not its digital root ' + digitalRoot(num));
  if (CATEGORIES.indexOf(category) === -1) fail(num + ': unknown category "' + category + '"');
  [math, title, desc].forEach((s, k) => { if (!s) fail(num + ': ' + ['reduction', 'title', 'description'][k] + ' is empty'); });
  r.forEach(s => { if (DASH.test(s)) fail(num + ': carries a dash'); });
  return { n: num, root: rt, math: math, title: title, category: category, desc: desc };
});
for (let n = 10; n <= 99; n++) if (!seen[n]) fail('compound ' + n + ' is missing');

const lines = entries.map(e => '    ' + e.n + ': ' + JSON.stringify({ root: e.root, math: e.math, title: e.title, category: e.category, desc: e.desc }) + ',');
lines[lines.length - 1] = lines[lines.length - 1].replace(/,$/, '');

const out = `/* number-matrix.js. The Book of Numbers: every compound from 10 to 99. V1.0.0

   GENERATED by tools/build-number-matrix.js from
   docs/source/book-of-numbers-matrix.csv, the owner's matrix of 19 October
   2026. Do not edit by hand: change the CSV and run the tool.

   THE PRINCIPLE THE OWNER SET. A single digit is where a number ends, not what
   it is. The double digit a reduction passes through on its way down is the
   number's own frequency, and it is read before the root: a 6 reached from 33
   is Master Number 33, and a 4 reached from 13 carries the debt of 13. The
   arithmetic that finds the compound lives in incommon-core.js (settle()) and
   numerology-content.js (fromName()); this file holds the writing, keyed by the
   compound, and reads nothing.

   Interpretation layer. No dashes. */
(function (root, factory) {
  if (typeof module === 'object' && module.exports) { module.exports = factory(); }
  else { root.NumberMatrix = factory(); }
}(typeof self !== 'undefined' ? self : this, function () {
  'use strict';

  var CATEGORIES = ${JSON.stringify(CATEGORIES)};

  var M = {
${lines.join('\n')}
  };

  return {
    VERSION: '1.0.0',
    CATEGORIES: CATEGORIES,
    entries: M,
    has: function (n) { return !!M[n]; },
    /* get(33) -> { n, root, math, title, category, desc, master, karmic } or null */
    get: function (n) {
      var e = M[n];
      if (!e) return null;
      return { n: +n, root: e.root, math: e.math, title: e.title, category: e.category, desc: e.desc,
        master: e.category === 'Master Number', karmic: e.category === 'Karmic Debt',
        auspicious: e.category === 'Elite Auspicious' };
    }
  };
}));
`;

if (process.argv.indexOf('--check') !== -1) {
  const cur = fs.existsSync(OUT) ? fs.readFileSync(OUT, 'utf8') : '';
  if (cur !== out) fail('app/number-matrix.js is not what the CSV generates; run node tools/build-number-matrix.js');
  console.log('build-number-matrix: app/number-matrix.js matches the CSV (' + entries.length + ' compounds)');
} else {
  fs.writeFileSync(OUT, out);
  console.log('build-number-matrix: wrote app/number-matrix.js (' + entries.length + ' compounds)');
}
