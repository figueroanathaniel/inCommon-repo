#!/usr/bin/env python3
"""Generate test vectors only; Swiss Ephemeris is not an app dependency.

Usage: PYTHONPATH=<pyswisseph directory> python tools/generate-client-swiss-reference.py <ephemeris directory>
Requires pyswisseph wrapping Swiss Ephemeris 2.10.03 and planetary/lunar
Swiss ephemeris files. Refuse a Moshier fallback for the osculating apogee.
"""
import json
import sys
from datetime import datetime
from pathlib import Path
import swisseph as swe

DATES = [
    '1975-07-15T12:00:00Z', '1987-11-22T03:15:00Z',
    '1994-02-17T05:37:00Z', '2000-01-01T12:00:00Z',
    '2006-04-02T07:30:00Z', '2012-06-21T18:45:00Z',
    '2024-04-08T18:00:00Z', '2026-10-25T12:00:00Z',
]
PLACES = [
    ('Edison', 40.51872, -74.4121), ('Seattle', 47.6062, -122.3321),
    ('Sydney', -33.8688, 151.2093), ('Kathmandu', 27.7172, 85.3240),
    ('Quito', -0.1807, -78.4678), ('Nairobi', -1.2921, 36.8219),
    ('Reykjavik', 64.1466, -21.9426), ('Longyearbyen', 78.2232, 15.6469),
    ('McMurdo', -77.8419, 166.6863),
]
if len(sys.argv) != 2:
    raise SystemExit(__doc__)
if swe.version != '2.10.03':
    raise SystemExit('Review reference version before changing the baseline: ' + swe.version)
swe.set_ephe_path(sys.argv[1])
rows = []
for instant in DATES:
    d = datetime.fromisoformat(instant.replace('Z', '+00:00'))
    jd = swe.julday(d.year, d.month, d.day, d.hour + d.minute / 60 + d.second / 3600)
    osc, flags = swe.calc_ut(jd, swe.OSCU_APOG, swe.FLG_SWIEPH)
    if not flags & swe.FLG_SWIEPH:
        raise SystemExit('Swiss lunar file missing; refusing fallback at ' + instant)
    row = {
        'utc': instant,
        'heliocentricOsculatingAscendingNodeDeg': {
            name: swe.nod_aps_ut(jd, getattr(swe, name.upper()), swe.NODBIT_OSCU,
                                 swe.FLG_SWIEPH | swe.FLG_HELCTR)[0][0]
            for name in ('Mercury', 'Venus', 'Mars', 'Jupiter', 'Saturn', 'Uranus', 'Neptune', 'Pluto')
        },
        'meanLunarNorthNodeDeg': swe.calc_ut(jd, swe.MEAN_NODE, swe.FLG_SWIEPH)[0][0],
        'meanLilithDeg': swe.calc_ut(jd, swe.MEAN_APOG, swe.FLG_SWIEPH)[0][0],
        'osculatingLilithDeg': osc[0],
        'solarLongitudeDeg': swe.calc_ut(jd, swe.SUN, swe.FLG_SWIEPH)[0][0],
        'lunarLongitudeDeg': swe.calc_ut(jd, swe.MOON, swe.FLG_SWIEPH)[0][0],
        'angles': [],
    }
    for name, lat, lon in PLACES:
        _, a = swe.houses_ex(jd, lat, lon, b'E', 0)
        sun = swe.calc_ut(jd, swe.SUN, swe.FLG_SWIEPH)[0]
        altitude = swe.azalt(jd, swe.ECL2HOR, (lon, lat, 0), 0, 0, sun[:3])[1]
        sun_lon, moon_lon = row['solarLongitudeDeg'], row['lunarLongitudeDeg']
        fortune = (a[0] + moon_lon - sun_lon if altitude >= 0 else a[0] + sun_lon - moon_lon) % 360
        spirit = (a[0] + sun_lon - moon_lon if altitude >= 0 else a[0] + moon_lon - sun_lon) % 360
        row['angles'].append({'place': name, 'latitude': lat, 'longitude': lon,
                              'asc': a[0], 'mc': a[1], 'vertex': a[3], 'sunAltitudeDeg': altitude,
                              'partOfFortune': fortune, 'partOfSpirit': spirit})
    rows.append(row)
out = Path(__file__).parent / 'fixtures/client-chart-swiss-reference.json'
out.write_text(json.dumps({
    'source': 'Swiss Ephemeris 2.10.03; generated by tools/generate-client-swiss-reference.py',
    'conventions': 'UTC to JD_UT; tropical ecliptic of date; planetary nodes nod_aps_ut NODBIT_OSCU FLG_SWIEPH|FLG_HELCTR; lunar points calc_ut MEAN_NODE/MEAN_APOG/OSCU_APOG FLG_SWIEPH; angles houses_ex Equal House E flags 0, latitude geodetic and longitude east positive.',
    'rows': rows,
}, indent=2) + '\n')
print(str(out))
